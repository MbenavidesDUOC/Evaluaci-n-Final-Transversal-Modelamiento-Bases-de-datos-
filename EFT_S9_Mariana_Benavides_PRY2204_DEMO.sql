CREATE TABLE ASOCIACION (
    id_asociacion NUMBER(5) NOT NULL,
    nombre_asociacion VARCHAR2(100) NOT NULL,
    fecha_creacion DATE NOT NULL,
    tipo_asociacion CHAR(1) NOT NULL,
    CONSTRAINT ASOCIACION_PK PRIMARY KEY (id_asociacion),
    CONSTRAINT ASOCIACION_CK_FECHA
        CHECK (fecha_creacion >= DATE '1980-12-31'),
    CONSTRAINT ASOCIACION_CK_TIPO
        CHECK (tipo_asociacion IN ('P', 'A'))
);

CREATE TABLE CLUB_FUTBOL (
    id_club NUMBER(6) NOT NULL,
    nombre_club VARCHAR2(80) NOT NULL,
    patrimonio NUMBER(15) NOT NULL,
    ubicacion_calle VARCHAR2(150) NOT NULL,
    tipo_club VARCHAR2(12) NOT NULL,
    CONSTRAINT CLUB_FUTBOL_PK PRIMARY KEY (id_club),
    CONSTRAINT CLUB_FUTBOL__UN UNIQUE (nombre_club),
    CONSTRAINT CLUB_FUTBOL_CK_TIPO
        CHECK (tipo_club IN ('Profesional', 'Amateur')),
    CONSTRAINT CLUB_FUTBOL_CK_PATRIMONIO
        CHECK (patrimonio >= 0)
);

CREATE TABLE REGION (
    id_region NUMBER(2) NOT NULL,
    nombre VARCHAR2(80) NOT NULL,
    CONSTRAINT REGION_PK PRIMARY KEY (id_region)
);

CREATE TABLE COMUNA (
    id_comuna NUMBER(5) NOT NULL,
    nombre VARCHAR2(80) NOT NULL,
    REGION_id_region NUMBER(2) NOT NULL,
    CONSTRAINT COMUNA_PK PRIMARY KEY (id_comuna),
    CONSTRAINT COMUNA_REGION_FK
        FOREIGN KEY (REGION_id_region)
        REFERENCES REGION (id_region)
);

CREATE TABLE ESCUELA_FUTBOL (
    id_escuela NUMBER(6) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    capacidad NUMBER(5) NOT NULL,
    fecha_fundacion DATE NOT NULL,
    CONSTRAINT ESCUELA_FUTBOL_PK PRIMARY KEY (id_escuela),
    CONSTRAINT ESCUELA_FUTBOL_CK_CAPACIDAD
        CHECK (capacidad > 0)
);

CREATE TABLE IDIOMA (
    id_idioma NUMBER(4) NOT NULL,
    nombre VARCHAR2(70) NOT NULL,
    CONSTRAINT IDIOMA_PK PRIMARY KEY (id_idioma),
    CONSTRAINT IDIOMA__NOMBRE UNIQUE (nombre)
);

CREATE TABLE NACIONALIDAD (
    id_nacion NUMBER(5)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 210 INCREMENT BY 2)
        NOT NULL,
    descripcion VARCHAR2(50) NOT NULL,
    CONSTRAINT NACIONALIDAD_PK PRIMARY KEY (id_nacion)
);

CREATE TABLE TRABAJADOR (
    id_trabajador NUMBER(10) NOT NULL,
    rut NUMBER(9) NOT NULL,
    dv_rut CHAR(1) NOT NULL,
    nombres VARCHAR2(80) NOT NULL,
    apellidos VARCHAR2(90) NOT NULL,
    sueldo_base NUMBER(15) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    genero VARCHAR2(30) NOT NULL,
    estado_civil VARCHAR2(30) NOT NULL,
    telefono_movil VARCHAR2(35) NOT NULL,
    direccion VARCHAR2(200) NOT NULL,
    correo VARCHAR2(200),
    COMUNA_id_comuna NUMBER(5) NOT NULL,
    NACIONALIDAD_id_nacion NUMBER(5) NOT NULL,
    CONSTRAINT TRABAJADOR_PK PRIMARY KEY (id_trabajador),
    CONSTRAINT TRABAJADOR__RUT UNIQUE (rut),
    CONSTRAINT TRABAJADOR_CK_SUELDO
        CHECK (sueldo_base >= 0),
    CONSTRAINT TRABAJADOR_COMUNA_FK
        FOREIGN KEY (COMUNA_id_comuna)
        REFERENCES COMUNA (id_comuna),
    CONSTRAINT TRABAJADOR_NACIONALIDAD_FK
        FOREIGN KEY (NACIONALIDAD_id_nacion)
        REFERENCES NACIONALIDAD (id_nacion)
);

CREATE TABLE JUGADOR (
    id_trabajador NUMBER(10) NOT NULL,
    puesto VARCHAR2(40) NOT NULL,
    total_premios NUMBER(15) DEFAULT 0 NOT NULL,
    anio_fin_amateur NUMBER(4),
    ASOCIACION_id_asociacion NUMBER(5) NOT NULL,
    ESCUELA_FUTBOL_id_escuela NUMBER(6),
    CONSTRAINT JUGADOR_PK PRIMARY KEY (id_trabajador),
    CONSTRAINT JUGADOR_CK_PREMIOS
        CHECK (total_premios >= 0),
    CONSTRAINT JUGADOR_TRABAJADOR_FK
        FOREIGN KEY (id_trabajador)
        REFERENCES TRABAJADOR (id_trabajador),
    CONSTRAINT JUGADOR_ASOCIACION_FK
        FOREIGN KEY (ASOCIACION_id_asociacion)
        REFERENCES ASOCIACION (id_asociacion),
    CONSTRAINT JUGADOR_ESCUELA_FUTBOL_FK
        FOREIGN KEY (ESCUELA_FUTBOL_id_escuela)
        REFERENCES ESCUELA_FUTBOL (id_escuela)
);

CREATE TABLE PERSONAL_PLANTA (
    id_trabajador NUMBER(10) NOT NULL,
    horas_trabajadas NUMBER(6,2),
    valor_hora_extra NUMBER(10,2),
    CLUB_FUTBOL_id_club NUMBER(6) NOT NULL,
    CONSTRAINT PERSONAL_PLANTA_PK PRIMARY KEY (id_trabajador),
    CONSTRAINT PERSONAL_PLANTA_TRABAJADOR_FK
        FOREIGN KEY (id_trabajador)
        REFERENCES TRABAJADOR (id_trabajador),
    CONSTRAINT PERSONAL_PLANTA_CLUB_FUTBOL_FK
        FOREIGN KEY (CLUB_FUTBOL_id_club)
        REFERENCES CLUB_FUTBOL (id_club)
);

CREATE TABLE JUGADOR_IDIOMA (
    nivel_dominio VARCHAR2(30) NOT NULL,
    JUGADOR_id_trabajador NUMBER(10) NOT NULL,
    IDIOMA_id_idioma NUMBER(4) NOT NULL,
    CONSTRAINT JUGADOR_IDIOMA_PK
        PRIMARY KEY (JUGADOR_id_trabajador, IDIOMA_id_idioma),
    CONSTRAINT JUGADOR_IDIOMA_JUGADOR_FK
        FOREIGN KEY (JUGADOR_id_trabajador)
        REFERENCES JUGADOR (id_trabajador),
    CONSTRAINT JUGADOR_IDIOMA_IDIOMA_FK
        FOREIGN KEY (IDIOMA_id_idioma)
        REFERENCES IDIOMA (id_idioma)
);

CREATE TABLE PERMANENCIA (
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    JUGADOR_id_trabajador NUMBER(10) NOT NULL,
    CLUB_FUTBOL_id_club NUMBER(6) NOT NULL,
    CONSTRAINT PERMANENCIA_PK
        PRIMARY KEY (fecha_inicio, JUGADOR_id_trabajador),
    CONSTRAINT PERMANENCIA_CK_FECHAS
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CONSTRAINT PERMANENCIA_JUGADOR_FK
        FOREIGN KEY (JUGADOR_id_trabajador)
        REFERENCES JUGADOR (id_trabajador),
    CONSTRAINT PERMANENCIA_CLUB_FUTBOL_FK
        FOREIGN KEY (CLUB_FUTBOL_id_club)
        REFERENCES CLUB_FUTBOL (id_club)
);

